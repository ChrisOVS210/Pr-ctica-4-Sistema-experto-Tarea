"""Train a tiny, illustrative logistic model and export constants for Arduino."""
import argparse
from pathlib import Path

import pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

BASE = Path(__file__).resolve().parent
FEATURES = ["Edad", "IMC", "Actividad", "Antecedentes"]
TARGET = "Obesidad"

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("csv", nargs="?", default=str(BASE / "Obesidad.csv"), help="CSV con Edad, IMC, Actividad, Antecedentes, Obesidad")
    parser.add_argument("--output", default=str(BASE / "Arduino" / "ObesidadEducativa" / "model_params.h"), help="archivo .h a incluir en el sketch")
    args = parser.parse_args()
    df = pd.read_csv(args.csv)
    df.columns = df.columns.str.strip()
    missing = [c for c in FEATURES + [TARGET] if c not in df.columns]
    if missing:
        raise SystemExit(f"Faltan columnas requeridas: {missing}")
    data = df[FEATURES + [TARGET]].apply(pd.to_numeric, errors="coerce").dropna()
    if len(data) < 20 or set(data[TARGET].unique()) != {0, 1}:
        raise SystemExit("Se requieren al menos 20 filas y etiquetas 0 y 1.")
    if not data["Antecedentes"].isin([0, 1]).all():
        raise SystemExit("Antecedentes debe ser 0/1 en el conjunto de entrenamiento.")

    scaler = StandardScaler()
    X = scaler.fit_transform(data[FEATURES])
    clf = LogisticRegression(max_iter=2000, random_state=17).fit(X, data[TARGET].astype(int))
    weights = clf.coef_[0]
    means = scaler.mean_
    scales = scaler.scale_
    mins = data[FEATURES].min().to_numpy()
    maxs = data[FEATURES].max().to_numpy()

    def array(values):
        def literal(value):
            rendered = f"{float(value):.10g}"
            if "." not in rendered and "e" not in rendered.lower():
                rendered += ".0"
            return rendered + "f"
        return ", ".join(literal(v) for v in values)
    header = f'''// Generated by train_model.py. Demo parameters; not clinically validated.
#ifndef MODEL_PARAMS_H
#define MODEL_PARAMS_H
const int MODEL_FEATURES = {len(FEATURES)};
const float MODEL_MEAN[MODEL_FEATURES] = {{{array(means)}}};
const float MODEL_SCALE[MODEL_FEATURES] = {{{array(scales)}}};
const float MODEL_MIN[MODEL_FEATURES] = {{{array(mins)}}};
const float MODEL_MAX[MODEL_FEATURES] = {{{array(maxs)}}};
const float MODEL_WEIGHT[MODEL_FEATURES] = {{{array(weights)}}};
const float MODEL_BIAS = {float(clf.intercept_[0]):.10g}f;
#endif
'''
    Path(args.output).write_text(header, encoding="utf-8")
    print(f"Modelo ilustrativo entrenado con {len(data)} filas; constantes exportadas a {args.output}.")
    print("El objetivo y el origen de las etiquetas deben verificarse antes de interpretar el resultado.")

if __name__ == "__main__":
    main()
